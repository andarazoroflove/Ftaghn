uint8_t GetFontTile(char c) {
    if (c >= '0' && c <= '9') return (uint8_t)(1 + (c - '0'));
    if (c >= 'A' && c <= 'Z') return (uint8_t)(11 + (c - 'A'));
    if (c >= 'a' && c <= 'z') return (uint8_t)(11 + (c - 'a'));
    switch(c) {
        case ':': return 37;
        case '!': return 38;
        case '-': return 39;
        case '+': return 40;
        case '.': return 41;
        case '/': return 42;
        case '?': return 43;
        case '(': return 44;
        case ')': return 45;
        case '<': return 46;
        case '>': return 47;
        case '*': return 48;
        default:  return 0; /* Space */
    }
}
